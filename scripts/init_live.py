#!/usr/bin/env python3
"""ONE-OFF (manual, owner-approved): prepare the always-on DB to take forecasts first (FORECASTS_LIVE=1).
- Replaces the always-on `forecasts` table (a stale copy from the Oct 30 outage) with the live table: same columns as core
  plus `synced`, identity seeded past the core max id so ids stay continuous and never collide.
- Copies the last 3 days of core forecasts (paths dropped) marked synced, and creates the latest_forecasts view.
Usage: CORE_URL=... HOT_URL=... python3 scripts/init_live.py [--dry-run]
Rollback: scripts/init_live.py --rollback copies unsynced rows to core and moves the core identity past them.
"""
import os, sys, psycopg
from psycopg.types.json import Jsonb
DRY = "--dry-run" in sys.argv
COLS = ["id", "symbol", "venue", "timeframe", "model", "as_of", "horizon_bars", "horizon_end", "context_bars", "sampling", "last_close",
        "prob_up", "expected_move_pct", "band_80_pct", "factlist", "percentiles", "paths", "runtime_sec", "created_at"]
JSONB = ("sampling", "factlist", "percentiles", "paths")
DDL = """create table forecasts (
  id bigint generated by default as identity primary key, symbol text not null, venue text, timeframe text not null, model text not null,
  as_of timestamptz not null, horizon_bars smallint, horizon_end timestamptz, context_bars smallint, sampling jsonb, last_close double precision,
  prob_up real, expected_move_pct real, band_80_pct real[], factlist jsonb, percentiles jsonb, paths jsonb, runtime_sec real,
  created_at timestamptz not null default now(), synced boolean not null default false, unique (symbol, timeframe, model, as_of))"""
VIEW = """create view latest_forecasts as select distinct on (symbol, timeframe) id, symbol, venue, timeframe, model, as_of, horizon_end,
  factlist, percentiles, created_at from forecasts order by symbol, timeframe, as_of desc"""

def conn(k): return psycopg.connect(os.environ[k], autocommit=True, prepare_threshold=None, connect_timeout=15)

def init():
    c, h = conn("CORE_URL"), conn("HOT_URL")
    mx = c.execute("select coalesce(max(id), 0) from forecasts").fetchone()[0]
    rows = c.execute(f"select {', '.join(COLS)} from forecasts where as_of > now() - interval '3 days' order by id").fetchall()
    c.close()
    print(f"core max id {mx}; {len(rows)} rows from the last 3 days to copy")
    cur = h.execute("select to_regclass('public.forecasts') is not null, (select count(*) from information_schema.columns where table_name = 'forecasts' and column_name = 'synced')").fetchone()
    print("always-on forecasts exists:", cur[0], "live already:", bool(cur[1]))
    if cur[1]: print("already initialised; nothing to do"); return
    if DRY: return
    with h.transaction():
        h.execute("drop view if exists latest_forecasts")
        h.execute("drop table if exists forecasts cascade")
        h.execute(DDL)
        h.execute("create index forecasts_latest_idx on forecasts (symbol, timeframe, as_of desc)")
        h.execute("create index forecasts_unsynced_idx on forecasts (id) where not synced")
        for r in rows:
            vals = [Jsonb([]) if k == "paths" else (Jsonb(v) if k in JSONB and v is not None else v) for k, v in zip(COLS, r)]
            h.execute(f"insert into forecasts ({', '.join(COLS)}, synced) values ({', '.join(['%s'] * len(COLS))}, true)", vals)
        h.execute("select setval(pg_get_serial_sequence('forecasts', 'id'), %s)", (mx + 1000,))
        h.execute(VIEW)
    print(f"done: {len(rows)} rows, next id {mx + 1001}")
    h.close()

def rollback():
    c, h = conn("CORE_URL"), conn("HOT_URL")
    rows = h.execute(f"select {', '.join(COLS)} from forecasts where not synced order by id").fetchall()
    print(f"{len(rows)} unsynced always-on rows")
    if not DRY:
        for r in rows:
            vals = [Jsonb(v) if k in JSONB and v is not None else v for k, v in zip(COLS, r)]
            c.execute(f"insert into forecasts ({', '.join(COLS)}) overriding system value values ({', '.join(['%s'] * len(COLS))}) on conflict do nothing", vals)
        if rows: h.execute("update forecasts set synced = true where id = any(%s)", ([r[0] for r in rows],))
        m = c.execute("select setval(pg_get_serial_sequence('forecasts', 'id'), (select max(id) from forecasts))").fetchone()[0]
        print("core identity now at", m)
    c.close(); h.close()

(rollback if "--rollback" in sys.argv else init)()
